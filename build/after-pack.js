// electron-builder afterPack hook: lists every top-level file and folder of the packaged app in
// build/app-files.nsh. The uninstaller removes exactly those (see build/installer.nsh) instead of
// wiping the whole install folder, so a folder picked in the installer that already held other
// files keeps them on uninstall.
const fs = require('fs');
const path = require('path');

module.exports = async function afterPack({ appOutDir }) {
  const target = (name) => `"$INSTDIR\\${name.replace(/\$/g, '$$$$')}"`;
  const lines = fs.readdirSync(appOutDir, { withFileTypes: true }).map((entry) => (entry.isDirectory()
    ? `  RMDir /r ${target(entry.name)}`
    : `  Delete ${target(entry.name)}`));
  fs.writeFileSync(path.join(__dirname, 'app-files.nsh'), [
    '; Generated by build/after-pack.js on every build. Do not edit.',
    '!macro hojichaRemoveAppFiles',
    ...lines,
    '!macroend',
    '',
  ].join('\r\n'));
};
