// electron-builder afterPack hook, run on the packaged app before the installer is made.
//
// 1. Drops Electron files Hojicha never uses (DirectX shader compiler, only needed for WebGPU).
// 2. Lists every top-level file and folder of the packaged app in build/app-files.nsh. The
//    uninstaller removes exactly those (see build/installer.nsh) instead of wiping the whole install
//    folder, so a folder picked in the installer that already held other files keeps them on uninstall.
const fs = require('fs');
const path = require('path');

const UNUSED = ['dxcompiler.dll', 'dxil.dll'];

module.exports = async function afterPack({ appOutDir }) {
  for (const name of UNUSED) fs.rmSync(path.join(appOutDir, name), { force: true });

  const target = (name) => `"$INSTDIR\\${name.replace(/\$/g, '$$$$')}"`;
  const lines = fs.readdirSync(appOutDir, { withFileTypes: true }).map((entry) => (entry.isDirectory()
    ? `  RMDir /r ${target(entry.name)}`
    : `  Delete ${target(entry.name)}`));
  // Also clean up the dropped files, which installs from before the trim (0.2.1 and older) still have.
  lines.push(...UNUSED.map((name) => `  Delete ${target(name)}`));
  fs.writeFileSync(path.join(__dirname, 'app-files.nsh'), [
    '; Generated by build/after-pack.js on every build. Do not edit.',
    '!macro hojichaRemoveAppFiles',
    ...lines,
    '!macroend',
    '',
  ].join('\r\n'));
};
